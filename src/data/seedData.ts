export function generateInitialAttendances(users: User[], schoolCode: string): Attendance[] {
  const today = getTodayDateString();
  const students = users.filter((u) => u.role === 'student' && u.schoolCode === schoolCode);

  return students.map((st, index) => {
    // Student 1: Present (self + teacher)
    if (index === 0) {
      return {
        id: `att-${st.id}-${today}`,
        studentId: st.id,
        studentName: st.name,
        nationalId: st.nationalId,
        schoolCode: st.schoolCode,
        className: st.className || 'الأول المتوسط',
        sectionName: st.sectionName || '1',
        date: today,
        selfCheckTime: '06:45',
        teacherMark: 'present',
        finalStatus: 'present',
        isTruant: false,
        parentMobile: st.parentMobile,
      };
    }
    // Student 2: Absent
    if (index === 1) {
      return {
        id: `att-${st.id}-${today}`,
        studentId: st.id,
        studentName: st.name,
        nationalId: st.nationalId,
        schoolCode: st.schoolCode,
        className: st.className || 'الأول المتوسط',
        sectionName: st.sectionName || '2',
        date: today,
        selfCheckTime: null,
        teacherMark: 'absent',
        finalStatus: 'absent',
        isTruant: false,
        parentMobile: st.parentMobile,
      };
    }
    // Student 3: Truancy demo (self checked present at 6:50, but teacher marked absent in class!)
    return {
      id: `att-${st.id}-${today}`,
      studentId: st.id,
      studentName: st.name,
      nationalId: st.nationalId,
      schoolCode: st.schoolCode,
      className: st.className || 'الأول المتوسط',
      sectionName: st.sectionName || '1',
      date: today,
      selfCheckTime: '06:50',
      teacherMark: 'absent',
      finalStatus: 'absent',
      isTruant: true,
      parentMobile: st.parentMobile,
    };
  });
}

